await run('Normal','2026-09-20');check('no clear-up without a preceding elevated notification',()=>assert.equal(mails.length,0));
await run('Not recommended','2026-09-21',true);check('dry run sends nothing and changes no state',()=>assert.equal(mails.length,0));
